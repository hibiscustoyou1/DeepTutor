import { access, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { loadTarget } from './lib/target.mjs';
import { loadCredentials } from './lib/ctcloud-credentials.mjs';

// Fork-only helper (not part of the upstream build): injects the ctcloud channel
// credentials into an already-built bundled runtime so the shipped app carries
// the real YL-3rd-Appcode/sk without either value ever living in the repo.
//
// Usage: node scripts/inject-ctcloud-secrets.mjs --target <id>
//
// Run it AFTER `build:runtime` and BEFORE `seal-runtime.mjs`/`package` — the
// seal step hashes and signs the runtime, so anything written after sealing
// breaks the manifest verification in the shell.
//
// Credentials: CTCLOUD_APP_CODE / CTCLOUD_APP_SECRET via env vars or the
// repo-root .env (see lib/ctcloud-credentials.mjs). The ctcloud channel imports
// the generated module and falls back to the in-repo placeholders ("ak"/"sk")
// when it is absent.

const target = await loadTarget();
const channelsDir = path.join(target.runtime, 'core', 'deeptutor', 'partners', 'channels');
try { await access(channelsDir); }
catch {
  throw new Error(`No bundled core at ${channelsDir} — run scripts/build-runtime.mjs first.`);
}
const credentials = await loadCredentials();
if (!credentials) {
  throw new Error('Missing CTCLOUD_APP_CODE / CTCLOUD_APP_SECRET (env vars or repo-root .env) — nothing to inject.');
}
await writeFile(
  path.join(channelsDir, '_ctcloud_secrets.py'),
  '"""Generated by scripts/inject-ctcloud-secrets.mjs — never commit real values."""\n'
  + `AGENT_APP_CODE = ${JSON.stringify(credentials.code)}\n`
  + `AGENT_APP_SECRET = ${JSON.stringify(credentials.secret)}\n`,
);
console.log(`Injected ctcloud credentials into the ${target.id} bundled core`);
